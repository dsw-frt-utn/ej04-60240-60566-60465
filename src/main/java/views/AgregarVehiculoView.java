    private void botonAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonAgregarActionPerformed

        String patente = txtPatente.getText();
        String modelo = txtModelo.getText();

        int anio = Integer.parseInt(txtAnio.getText());
        double carga = Double.parseDouble(txtCarga.getText());


        Marca marca = new Marca(txtMarca.getText(), "Desconocido");


        String codigo = comboSucursal.getSelectedItem().toString();

        Sucursal sucursal = Controlador.buscarSucursalPorCodigo(codigo);

        String tipo = comboTipo.getSelectedItem().toString();

        Vehiculo v;


        if(tipo.equals("Electrico")){

            double kwh = Double.parseDouble(txtKwh.getText());

            v = new VehiculoElectrico(patente, marca, modelo, anio, carga, sucursal, kwh);

        }else{

            double km = Double.parseDouble(txtKmLitro.getText());
            double extra = Double.parseDouble(txtLitrosExtra.getText());

            v = new VehiculoCombustible(patente, marca, modelo, anio, carga, sucursal, km, extra);
        }


        Controlador.agregarVehiculo(v);


        javax.swing.JOptionPane.showMessageDialog(this, "Vehiculo agregado");
        
        limpiarCampos();
    }//GEN-LAST:event_botonAgregarActionPerformed

    private void comboTipoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_comboTipoActionPerformed
        String tipo = comboTipo.getSelectedItem().toString();

        if(tipo.equals("Electrico")){

            txtKwh.setVisible(true);
            lblKwh.setVisible(true);

            txtKmLitro.setVisible(false);
            txtLitrosExtra.setVisible(false);
            lblKmLitro.setVisible(false);
            lblLitrosExtra.setVisible(false);

        } else {

            txtKwh.setVisible(false);
            lblKwh.setVisible(false);

            txtKmLitro.setVisible(true);
            txtLitrosExtra.setVisible(true);
            lblKmLitro.setVisible(true);
            lblLitrosExtra.setVisible(true);
        }
    }//GEN-LAST:event_comboTipoActionPerformed

